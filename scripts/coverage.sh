#!/bin/sh
# coverage.sh keeps the coverage block of README.md honest.
#
#   ./scripts/coverage.sh           print the block
#   ./scripts/coverage.sh --write   replace it in README.md
#   ./scripts/coverage.sh --check   exit 1 when README.md is behind (CI)
#
# A number in a README is wrong the day after somebody writes it, so this is a
# generator with a check instead of a paragraph and hope.
set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$root"

profile=$(mktemp)
trap 'rm -f "$profile"' EXIT

go test -coverprofile="$profile" ./... >/dev/null 2>&1
total=$(go tool cover -func="$profile" | awk '/^total:/ {print $3}' | tr -d '%')
[ -n "$total" ] || { echo "coverage: no total" >&2; exit 1; }

# a colour judges the number, so nobody has to read a table to see it is bad
colour=critical
total_int=${total%%.*}
[ "$total_int" -ge 80 ] && colour=brightgreen
[ "$total_int" -ge 60 ] && [ "$colour" = critical ] && colour=green
[ "$total_int" -ge 40 ] && [ "$colour" = critical ] && colour=yellow

block=$(mktemp)
trap 'rm -f "$profile" "$block"' EXIT
{
	# one line, in the same block as the other badges: a comment line between
	# images would end the paragraph and put the badge on a row of its own
	printf '[![coverage](https://img.shields.io/badge/coverage-%s%%25-%s)](#what-it-does)<!-- coverage: generated by scripts/coverage.sh -->\n' "$total" "$colour"
} > "$block"

case "${1:-}" in
--write)
	python3 - "$block" <<'PY'
import pathlib, re, sys
readme = pathlib.Path("README.md")
body = readme.read_text()
line = pathlib.Path(sys.argv[1]).read_text().strip()
pattern = re.compile(r"^\[!\[coverage\].*$", re.M)
if pattern.search(body):
    body = pattern.sub(line, body, count=1)
else:
    # the badge goes into the badge row, right below the license
    body = body.replace("(LICENSE)\n", "(LICENSE)\n" + line + "\n", 1)
readme.write_text(body)
PY
	echo "coverage: $total% written to README.md"
	;;
--check)
	if ! grep -qF "coverage-$total%25-$colour" README.md; then
		echo "coverage: README.md says" >&2
		grep -o 'coverage-[0-9.]*%25-[a-z]*' README.md >&2 || echo "  nothing" >&2
		echo "coverage: the code says $total% ($colour): run ./scripts/coverage.sh --write" >&2
		exit 1
	fi
	echo "coverage: README.md is current ($total%)"
	;;
*)
	cat "$block"
	;;
esac
